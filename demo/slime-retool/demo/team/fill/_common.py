"""Shared helpers for fill/NN_slug.py scripts.

A fill script reads kit files and writes build/NN_slug.data.sh: bash assignments
that beats/NN_slug.sh reads. Every variable starts with the slug in capitals
(fill/03_stage.py writes STAGE_*), so beats never collide.

Start every fill script with these lines (python -I keeps the script's directory
off sys.path, so add it explicitly):

    import pathlib, sys
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    from _common import Data, check_typed, manifest_lines  # and what else you need

    d = Data(__file__)
    d.set("STAGE_JOB_SECS", 109)
    d.array("STAGE_STORAGE_LINES", lines)
    d.write()

FRAMEWORK.md has the full API.
"""

import json
import os
import pathlib
import re
import sys
import tempfile
from datetime import datetime

TEAM = pathlib.Path(__file__).resolve().parents[1]   # demo/team
KIT = TEAM.parents[1]                                 # slime-retool
RUNS = KIT / "runs"
MANIFESTS = KIT / "manifests"
FUNCTIONS = KIT / "functions"
BUILD = TEAM / "build"

_NAME_RE = re.compile(r"[A-Z][A-Z0-9_]*")


# --- bash quoting (v1's fill_demo.py) -------------------------------------------------------

def q(value) -> str:
    """Single-quote a value for bash."""
    return "'" + str(value).replace("'", "'\"'\"'") + "'"


def arr(values) -> str:
    """A bash array literal of single-quoted values."""
    return "(" + " ".join(q(v) for v in values) + ")"


# --- data files -------------------------------------------------------------------------------

class Data:
    """The variables of one beat; write() saves them to build/NN_slug.data.sh."""

    def __init__(self, script_file):
        path = pathlib.Path(script_file).resolve()
        m = re.fullmatch(r"(\d\d)_([a-z0-9_]+)\.py", path.name)
        if not m:
            raise SystemExit(f"{path.name}: fill scripts are named NN_slug.py (slug: a-z, 0-9, _)")
        self.script = path.name
        self.nn, self.slug = m.group(1), m.group(2)
        self.prefix = self.slug.upper() + "_"
        self.out = BUILD / f"{self.nn}_{self.slug}.data.sh"
        self._lines = {}
        self._sources = []

    def _name(self, name: str) -> str:
        if not _NAME_RE.fullmatch(name):
            raise SystemExit(f"{self.script}: {name!r} is not a bash variable name in capitals")
        if not name.startswith(self.prefix):
            raise SystemExit(f"{self.script}: {name!r} must start with {self.prefix!r} (the beat's slug)")
        if name in self._lines:
            raise SystemExit(f"{self.script}: {name} is set twice")
        return name

    def set(self, name: str, value) -> None:
        """A scalar. ints are written bare (usable in (( ))); everything else is quoted."""
        name = self._name(name)
        if isinstance(value, bool):
            value = int(value)
        self._lines[name] = f"{name}={value}" if isinstance(value, int) else f"{name}={q(value)}"

    def array(self, name: str, values) -> None:
        """A bash array, one element per item."""
        name = self._name(name)
        values = list(values)
        for v in values:
            if isinstance(v, (list, tuple, dict)):
                raise SystemExit(f"{self.script}: {name} holds a nested value {v!r}")
        self._lines[name] = f"{name}={arr(values)}"

    def source(self, *paths) -> None:
        """Record kit files this beat's data comes from (listed in the data file's header)."""
        for p in paths:
            p = pathlib.Path(p)
            self._sources.append(str(p.resolve().relative_to(KIT)) if p.is_absolute() else str(p))

    def write(self) -> pathlib.Path:
        BUILD.mkdir(exist_ok=True)
        head = [f"# Generated by fill/{self.script}; do not edit. Rerun build.sh (or run.sh {self.nn})."]
        if self._sources:
            head.append("# Sources: " + ", ".join(self._sources))
        text = "\n".join(head + list(self._lines.values())) + "\n"
        fd, tmp = tempfile.mkstemp(prefix=f".{self.out.name}.", dir=BUILD)
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, self.out)
        print(f"wrote {self.out.relative_to(TEAM)}: {len(self._lines)} variables")
        return self.out


# --- reading kit files ------------------------------------------------------------------------

def kit_path(rel) -> pathlib.Path:
    """A path relative to the kit root (or an absolute path, unchanged)."""
    p = pathlib.Path(rel)
    return p if p.is_absolute() else KIT / p


def read_lines(rel) -> list:
    """The file's lines, without line endings."""
    return kit_path(rel).read_text().splitlines()


def strip_header(lines) -> list:
    """Drop the leading block of # comment lines (the kit-internal header) and blank lines after it."""
    i = 0
    while i < len(lines) and lines[i].lstrip().startswith("#"):
        i += 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    return lines[i:]


def manifest_lines(rel, header=False) -> list:
    """A file's lines for typing in vim, without its leading comment header unless header=True."""
    lines = read_lines(rel)
    return lines if header else strip_header(lines)


def load_yaml(rel):
    import yaml  # PyYAML, in the venv
    return yaml.safe_load(kit_path(rel).read_text())


def load_json(rel):
    return json.loads(kit_path(rel).read_text())


def check_typed(lines, rel, script=None) -> None:
    """Exit with an error unless every line is a real line of the file, in the file's order.

    Lines may be skipped (for example, comments left out), but none may be changed,
    invented, or moved. Call it on everything a beat types in vim.
    """
    real = read_lines(rel)
    who = script or pathlib.Path(sys.argv[0]).name
    pos = 0
    for n, line in enumerate(lines, 1):
        try:
            pos = real.index(line, pos) + 1
        except ValueError:
            where = "is not a line of" if line not in real else "is out of order in"
            raise SystemExit(f"{who}: typed line {n} {where} {rel}: {line!r}")


def check_in_file(text, rel, script=None) -> None:
    """Exit with an error unless text (one line or several) appears verbatim in the file."""
    if text not in kit_path(rel).read_text():
        who = script or pathlib.Path(sys.argv[0]).name
        raise SystemExit(f"{who}: not found verbatim in {rel}: {text[:120]!r}")


def find_line(lines, needle, start=1) -> int:
    """The 1-based number of the first line (from start) that contains needle."""
    for i in range(start - 1, len(lines)):
        if needle in lines[i]:
            return i + 1
    raise SystemExit(f"{pathlib.Path(sys.argv[0]).name}: no line contains {needle!r}")


# --- formatting -------------------------------------------------------------------------------

def fmt_int(n) -> str:
    """17398 -> '17,398'."""
    return f"{int(n):,}"


def iso(s: str) -> datetime:
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def secs(a: str, b: str) -> int:
    """Whole seconds from ISO time a to ISO time b."""
    return round((iso(b) - iso(a)).total_seconds())


def max_width(lines, limit=120, what="line") -> None:
    """Exit with an error if a line is wider than limit columns (simple check: no escapes, no emoji)."""
    for line in lines:
        if len(line) > limit:
            raise SystemExit(f"{pathlib.Path(sys.argv[0]).name}: {what} wider than {limit} columns ({len(line)}): {line!r}")
