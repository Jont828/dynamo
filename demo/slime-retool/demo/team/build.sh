# Build the standalone team replay.
#
#   ./build.sh                      every beat except 99 -> slime-retool-team-demo.sh
#   ./build.sh 03 04                just these beats (for testing) -> tmp/build-03-04.sh
#   ./build.sh -o OUT.sh [NN ...]   choose the output file
#
# 1. Runs each selected beat's fill/NN_slug.py with the venv Python (-I); each writes
#    build/NN_slug.data.sh. The first fill script that fails stops the build.
# 2. Concatenates lib.sh, the data files, the beat files, and a main into one
#    script that needs nothing else (deterministic: same inputs, same bytes), and
#    checks that it parses.
set -euo pipefail

TEAM_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY="${PY:-python3}"   # any Python 3.10+ with PyYAML
fail() { printf 'build.sh: %s\n' "$*" >&2; exit 1; }

OUT=""
ARGS=()
while (( $# )); do
    case "$1" in
        -o) OUT="${2:?-o needs a file}"; shift 2 ;;
        -h|--help) sed -n '4,16p' "$0"; exit 0 ;;
        *) ARGS+=("$1"); shift ;;
    esac
done

ALL=()
for f in "$TEAM_DIR"/beats/[0-9][0-9]_*.sh; do
    [[ -e "$f" ]] || continue
    b="${f##*/}"
    ALL+=("${b%%_*}")
done

SEL=()
if (( ${#ARGS[@]} )); then
    for a in "${ARGS[@]}"; do
        [[ "$a" =~ ^[0-9]+$ ]] || fail "beats are numbers (03 or 3), not '$a'"
        printf -v nn '%02d' "$((10#$a))"
        ls "$TEAM_DIR"/beats/"$nn"_*.sh >/dev/null 2>&1 || fail "no beats/${nn}_*.sh"
        SEL+=("$nn")
    done
    if [[ -z "$OUT" ]]; then
        mkdir -p "$TEAM_DIR/tmp"
        OUT="$TEAM_DIR/tmp/build-$(IFS=-; echo "${SEL[*]}").sh"
    fi
else
    for b in ${ALL[@]+"${ALL[@]}"}; do
        if [[ "$b" != 99 ]]; then SEL+=("$b"); fi
    done
    [[ -n "$OUT" ]] || OUT="$TEAM_DIR/slime-retool-team-demo.sh"
fi
(( ${#SEL[@]} )) || fail "no beats to build (beats/ has no NN_slug.sh files)"
case "$OUT" in /*) ;; *) OUT="$PWD/$OUT" ;; esac

# 1. Fill.
for nn in "${SEL[@]}"; do
    for f in "$TEAM_DIR"/fill/"$nn"_*.py; do
        [[ -e "$f" ]] || continue
        if ! "$PY" -I "$f"; then
            fail "FAILED: fill/${f##*/} (beat $nn). Nothing was built; fix it and rerun."
        fi
    done
done

# 2. Concatenate. Data files come before beat files; both in NN order.
TMP="$OUT.tmp.$$"
{
    cat <<'EOF'
