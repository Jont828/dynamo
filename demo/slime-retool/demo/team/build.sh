# ============================================================================
# Slime ReTool + Dynamo on AKS: the team replay. A cluster-free replay of one
# real run (runs/run1, KV-aware routing) and its round-robin baseline (runs/rr1):
# Slime trains Qwen3-4B with GRPO on ReTool in a KubeRay RayJob while a Dynamo
# DynamoGraphDeployment serves every turn of every rollout, on one ND96isr H100 v5
# node with Azure Managed Lustre for storage.
# ============================================================================
#
# GENERATED by demo/team/build.sh from lib.sh, build/*.data.sh (written by
# fill/*.py from the kit's runs/ and manifests/), and beats/*.sh. Don't edit this
# file: edit those and rerun build.sh. Nothing here touches a cluster.
#
# Usage: bash slime-retool-team-demo.sh [NN ...]   (FAST=1 skips the pauses)
# Record with: ./record.sh   (120x32, fern-code theme, a chapter marker per beat)
set -euo pipefail
EOF
    printf '\n# ---- lib.sh ----\n'
    cat "$TEAM_DIR/lib.sh"
    # Every beat's data (as run.sh sources it); 99's only when 99 is built.
    for f in "$TEAM_DIR"/build/[0-9][0-9]_*.data.sh; do
        [[ -e "$f" ]] || continue
        b="${f##*/}"
        if [[ "${b%%_*}" == 99 && " ${SEL[*]} " != *" 99 "* ]]; then continue; fi
        printf '\n# ---- build/%s ----\n' "$b"
        cat "$f"
    done
    for nn in "${SEL[@]}"; do
        for f in "$TEAM_DIR"/beats/"$nn"_*.sh; do
            [[ -e "$f" ]] || continue
            printf '\n# ---- beats/%s ----\n' "${f##*/}"
            cat "$f"
        done
    done
    printf '\n# ---- main ----\n'
    printf 'DEMO_BEATS=(%s)\n' "${SEL[*]}"
    printf 'if (( $# )); then demo_main "$@"; else demo_main "${DEMO_BEATS[@]}"; fi\n'
} > "$TMP"

if ! /bin/bash -n "$TMP"; then
    rm -f "$TMP"
    fail "the concatenated script doesn't parse (see the error above)"
fi
chmod +x "$TMP"
mv "$TMP" "$OUT"
echo "built ${OUT#"$TEAM_DIR"/}: beats ${SEL[*]}, $(wc -l < "$OUT" | tr -d ' ') lines"
