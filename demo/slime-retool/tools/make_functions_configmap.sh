#!/usr/bin/env bash
# Build manifests/functions.yaml (ConfigMap slime-retool-functions) from functions/.
# The RayJob mounts it at /opt/slime-functions, which is on PYTHONPATH.
set -euo pipefail
KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
{
  echo "# Generated by tools/make_functions_configmap.sh from functions/. Edit those files, not this one."
  kubectl create configmap slime-retool-functions --dry-run=client -o yaml \
    --from-file="$KIT/functions/generate_with_retool.py" \
    --from-file="$KIT/functions/tool_sandbox.py" \
    --from-file="$KIT/functions/weight_permissions.py"
} > "$KIT/manifests/functions.yaml"
echo "wrote $KIT/manifests/functions.yaml"
